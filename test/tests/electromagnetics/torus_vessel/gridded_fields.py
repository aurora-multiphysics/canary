"""
Writes axisymmetric source fields on an (R, Z) grid in the form torus_vessel.i
reads: one PiecewiseMultilinear data file per field over (R, Z, t), a CSV
of the times, and a MOOSE input converting them to the 2D ExodusII time series
read by SolutionUserObject, with x = R and y = Z.

Fields, all per the FreeGS conventions described in vde/freegsnke_source.py:

    dpsi_dt  rate of change of the poloidal source flux per radian [Wb/(rad s)]
    b_r      radial source field [T]
    b_z      vertical source field [T]
    b_phi    toroidal field [T]
"""

import os

import numpy as np

FIELDS = ("dpsi_dt", "b_r", "b_z", "b_phi")


def write_fields(directory, R, Z, times, fields, file_base="source"):
    """
    Write fields[name] of shape (n_times, n_R, n_Z), for each name in FIELDS,
    sampled at (R[i], Z[j], times[t]). R and Z must be uniformly spaced so that
    the conversion mesh nodes coincide with the grid.
    """
    R = np.asarray(R, dtype=float)
    Z = np.asarray(Z, dtype=float)
    times = np.asarray(times, dtype=float)
    shape = (len(times), len(R), len(Z))
    for name in FIELDS:
        if np.shape(fields[name]) != shape:
            raise ValueError(f"Field {name} has shape {np.shape(fields[name])}, expected {shape}.")
    if not (np.allclose(np.diff(R), R[1] - R[0]) and np.allclose(np.diff(Z), Z[1] - Z[0])):
        raise ValueError("R and Z must be uniformly spaced.")

    os.makedirs(directory, exist_ok=True)
    for name in FIELDS:
        _write_gridded(os.path.join(directory, f"{file_base}_{name}.txt"), R, Z, times, fields[name])
    np.savetxt(
        os.path.join(directory, f"{file_base}_times.csv"),
        times,
        header="time",
        comments="",
        fmt="%.17g",
    )
    with open(os.path.join(directory, f"{file_base}.i"), "w") as f:
        f.write(_conversion_input(R, Z, times, file_base))


def _write_gridded(path, R, Z, times, values):
    """Write values[t, i, j] at (R[i], Z[j], times[t]) in PiecewiseMultilinear format."""
    with open(path, "w") as f:
        for axis, coords in (("X", R), ("Y", Z), ("T", times)):
            f.write(f"AXIS {axis}\n")
            f.write(" ".join(f"{c:.17g}" for c in coords) + "\n")
        f.write("DATA\n")
        # PiecewiseMultilinear orders data with the first axis varying fastest.
        for value in np.transpose(values, (0, 2, 1)).ravel():
            f.write(f"{value:.17g}\n")


def _conversion_input(R, Z, times, file_base):
    """
    MOOSE input writing the gridded fields to a 2D ExodusII time series. The
    mesh nodes coincide with the grid, so first-order Lagrange variables hold
    the recorded values exactly.
    """
    aux_variables = "".join(f"  [{name}]\n  []\n" for name in FIELDS)
    functions = "".join(
        f"  [{name}]\n"
        f"    type = PiecewiseMultilinear\n"
        f"    data_file = {file_base}_{name}.txt\n"
        f"  []\n"
        for name in FIELDS
    )
    aux_kernels = "".join(
        f"  [{name}]\n"
        f"    type = FunctionAux\n"
        f"    variable = {name}\n"
        f"    function = {name}\n"
        f"    execute_on = 'INITIAL TIMESTEP_END'\n"
        f"  []\n"
        for name in FIELDS
    )
    return f"""# Generated by gridded_fields.py. Converts axisymmetric source fields on
# the (R, Z) grid to a 2D ExodusII time series, with x = R and y = Z.
[Mesh]
  type = GeneratedMesh
  dim = 2
  nx = {len(R) - 1}
  ny = {len(Z) - 1}
  xmin = {R[0]:.17g}
  xmax = {R[-1]:.17g}
  ymin = {Z[0]:.17g}
  ymax = {Z[-1]:.17g}
[]

[Problem]
  solve = false
[]

[AuxVariables]
{aux_variables}[]

[Functions]
{functions}[]

[AuxKernels]
{aux_kernels}[]

[Executioner]
  type = Transient
  start_time = {times[0]:.17g}
  end_time = {times[-1]:.17g}
  [TimeStepper]
    type = CSVTimeSequenceStepper
    file_name = {file_base}_times.csv
    column_name = time
  []
[]

[Outputs]
  exodus = true
[]
"""
